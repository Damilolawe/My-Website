import test from "node:test";
import assert from "node:assert/strict";
import {readFile} from "node:fs/promises";
import {templates,sampleForTemplate,types} from "../shared/model.mjs";
import {minimumTier,templateFitsTier} from "../shared/tiers.mjs";
import {renderSite} from "../shared/render.mjs";
import {uploadedDesigns} from "../shared/uploaded-designs.mjs";
import {originalDirections} from "../shared/refero-originals.mjs";

test("the 14 autogenerated concepts were removed and all 18 actual MD-matched designs exist",()=>{
 assert.equal(templates.length,38);
 assert.equal(originalDirections.length,5);
 assert.equal(uploadedDesigns.length,18);
 assert.equal(new Set(uploadedDesigns.map(x=>x.id)).size,18);
 assert.equal(new Set(templates.map(x=>x.id)).size,38);
 for(const source of uploadedDesigns){
   assert(templates.some(t=>t.id===source.id),source.id+" missing from catalog");
   assert(/^DESIGN \(\d+\)\.md$/.test(source.source),source.id+" source filename missing");
   assert(source.reference&&source.layout&&source.bg&&source.accent,source.id+" missing source-based tokens");
 }
 assert.equal(templates.filter(t=>minimumTier(t.id)==="starter").length,6);
 assert.equal(templates.filter(t=>minimumTier(t.id)==="signature").length,32);
 assert.equal(templates.filter(t=>templateFitsTier(t.id,"signature")).length,38);
 assert.equal(templates.filter(t=>templateFitsTier(t.id,"premium")).length,38);
});

test("all 18 uploaded-MD builds have unique architecture, use validated content and support demo modes",()=>{
 const markers=new Set();
 for(const d of uploadedDesigns){
  const sample=sampleForTemplate(d.id);
  const html=renderSite(sample,{sample:true});
  assert(html.startsWith("<!doctype html>"),d.id);
  assert(html.includes('data-architecture="'+d.layout+'"'),d.id+" layout lost");
  assert(html.includes("md-"+d.id+"-hero"),d.id+" missing authored hero");
  assert(html.includes("FICTIONAL TEMPLATE DEMO"),d.id+" fake demo disclaimer missing");
  assert(html.includes('id="work"'),d.id+" work section missing");
  assert(html.includes("contact-setup-note"),d.id+" no unverified contact links");
  assert(html.includes("prefers-reduced-motion:reduce"),d.id+" reduced motion unavailable");
  assert(!html.includes("<script"),d.id+" executable scripts forbidden");
  assert(html.length<250000,d.id+" publication-size limit exceeded "+html.length);
  markers.add(d.layout);
 }
 assert.equal(markers.size,18);
});

test("source-based templates preserve customer media, copy escaping and direct links",()=>{
 for(const d of uploadedDesigns){
  const v=sampleForTemplate(d.id,"Creative portfolio");
  v.content.name="<script>alert(1)</script>";
  v.content.headline="<img src=x onerror=alert(2)>";
  v.content.cards=[{title:"Original work",description:"An independent project",url:"javascript:alert(2)"}];
  v.content.photoIds=["11111111-1111-4111-8111-111111111111"];
  const html=renderSite(v);
  assert(html.includes("&lt;script&gt;alert(1)&lt;/script&gt;"),d.id);
  assert(html.includes("&lt;img src=x onerror=alert(2)&gt;"),d.id);
  assert(!html.includes("javascript:alert"),d.id);
  assert(html.includes("/api/assets/11111111-1111-4111-8111-111111111111"),d.id);
 }
});

